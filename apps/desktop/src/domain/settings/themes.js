function palette(colors) {
  const mix = (color, amount) =>
    `color-mix(in srgb, ${color} ${amount}%, ${colors.bg})`;
  return {
    accent: colors.accent,
    solid: colors.solid,
    hover: colors.solidHover,
    tokens: {
      bg: colors.bg,
      sidebar: colors.sidebar,
      panel: colors.panel,
      hover: colors.hover,
      border: colors.border,
      muted: colors.muted,
      text: colors.text,
      "secondary-text": mix(colors.text, 80),
      scrollbar: colors.border,
      "changes-bg": colors.bg,
      "diff-heading-bg": colors.sidebar,
      "composer-bg": colors.panel,
      "composer-border": colors.border,
      "popover-bg": colors.panel,
      "popover-border": colors.border,
      success: colors.success,
      deletion: colors.danger,
      danger: colors.danger,
      warning: colors.warning,
      "warning-bg": mix(colors.warning, 10),
      "warning-border": mix(colors.warning, 28),
      "error-bg": mix(colors.danger, 10),
      "error-border": mix(colors.danger, 28),
      "added-text": colors.success,
      "added-bg": mix(colors.success, 12),
      "removed-text": colors.danger,
      "removed-bg": mix(colors.danger, 12),
      "syntax-comment": colors.comment,
      "syntax-keyword": colors.keyword,
      "syntax-string": colors.string,
      "syntax-number": colors.number,
      "syntax-property": colors.property,
      "syntax-type": colors.type,
      ...colors.tokens,
    },
  };
}

